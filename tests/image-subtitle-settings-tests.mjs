import { installDom } from "./dom-environment.mjs";
const dom = installDom();
import assert from "node:assert/strict";

const element = id => document.getElementById(id);
const storage = { get: key => localStorage.getItem(key), set: (key, value) => localStorage.setItem(key, value) };
const context = await import("../dist/esm/player/settings.js");
const button = element("imageSubtitleMode");
context.initSettingsAutosave();
context.initSettingsAutosave();
assert.equal(element("removeCandidateAfterAddEnabled").checked, false);
assert.equal(button.textContent, "All text");
button.click();
assert.equal(button.value, "timed");
assert.equal(button.getAttribute("aria-pressed"), "true");
assert.equal(JSON.parse(storage.get("subtitlePlayerSettings")).imageSubtitleMode, "timed");
context.applyLanguage("ru");
assert.equal(button.textContent, "По времени");
storage.set("subtitlePlayerSettings", JSON.stringify({ imageSubtitleMode: "timed", includeImageSubtitle: false }));
button.value = "all";
context.loadSettings();
assert.equal(button.value, "timed");
assert.equal(button.disabled, true);
storage.set("subtitlePlayerSettings", JSON.stringify({ removeCandidateAfterAddEnabled: true }));
context.loadSettings();
assert.equal(element("removeCandidateAfterAddEnabled").checked, true);
element("removeCandidateAfterAddEnabled").checked = false;
context.saveSettingsLocal({ silent: true });
assert.equal(JSON.parse(storage.get("subtitlePlayerSettings")).removeCandidateAfterAddEnabled, false);
element("includeImageSubtitle").checked = true;
element("includeImageSubtitle").dispatchEvent(new Event("change"));
assert.equal(button.disabled, false);
storage.set("subtitlePlayerSettings", "{}");
context.loadSettings();
assert.equal(button.value, "all");
assert.equal(button.textContent, "Весь текст");
button.click();
button.click();
assert.equal(button.value, "all");
console.log("Image subtitle mode toggle, persistence, migration, and translation tests passed");

clearTimeout(context.settingsAutosaveTimerState.value);
dom.window.close();
