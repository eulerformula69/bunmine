import assert from "node:assert/strict";
import { installDom } from "./dom-environment.mjs";

const dom = installDom("library");
const { requireElement } = await import("../dist/esm/core/elements.js");
assert.throws(() => requireElement("#missing-element", window.HTMLElement), /#missing-element/);
assert.throws(() => requireElement("#seriesGrid", window.HTMLInputElement), /wrong type/);
const library = await import("../dist/esm/library/library.js");
const hostile = '<img src=x onerror="alert(1)">';
const card = library.renderSeriesCard({ id: 1, title: hostile, episodesCount: 2, completedEpisodes: 1 });
assert.equal(card.querySelector("h3").textContent, hostile);
assert.equal(card.querySelectorAll("img").length, 0);
assert.equal(card.querySelector("[data-completed-episodes]").textContent, "1");
const episode = { id: 2, title: hostile, hasVideo: true, hasSubtitle: false, completed: true };
const row = library.renderEpisodeRow(episode);
assert.equal(row.querySelector("h3").textContent, hostile);
assert.equal(row.querySelector("input").checked, true);
assert.equal(row.querySelectorAll("img").length, 0);
const file = library.renderFileRow({ ...episode, hasVideo: false, videoFilename: hostile });
assert.equal(file.querySelector("p").textContent, hostile);
assert.equal(file.querySelector(".subtitle-file-action").disabled, true);
assert.ok(file.querySelector(".delete-missing-episode-btn"));

const bulk = await import("../dist/esm/library/bulk-subtitle-view.js");
const state = await import("../dist/esm/library/library-state.js");
const candidate = { filename: hostile, downloadUrl: "https://example.com/test.srt", releaseLabel: hostile };
const plan = { items: [{ episodeId: '2" onclick="alert(1)', episodeTitle: hostile, status: "ready", selected: candidate, candidates: [candidate] }] };
state.currentBulkSubtitlePlanState.value = plan;
bulk.renderBulkSubtitlePlan(plan);
const list = document.getElementById("bulkSubtitleList");
assert.ok(list.querySelector(".bulk-subtitle-title").textContent.includes(hostile));
assert.equal(list.querySelectorAll("img, [onclick], [onerror]").length, 0);
assert.equal(list.querySelector("input").dataset.episodeId, plan.items[0].episodeId);
assert.equal(list.querySelector("input").checked, true);
assert.equal(list.querySelectorAll("option")[1].selected, true);
assert.equal(bulk.getSelectedBulkSubtitleItems().length, 1);
state.isBulkSubtitleDownloadingState.value = true;
bulk.renderBulkSubtitlePlan(plan);
assert.equal(list.querySelector("input").disabled, true);
assert.equal(list.querySelector("select"), null);
dom.window.close();
