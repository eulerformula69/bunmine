import assert from 'node:assert/strict';
import {installDom} from './dom-environment.mjs';
const dom=installDom();
const {state}=await import('../dist/esm/core/state.js');
const {video}=await import('../dist/esm/core/dom.js');
const {playMedia}=await import('../dist/esm/video/media-playback.js');
const errors=[];
await playMedia({play:async()=>{throw new DOMException('cancelled','AbortError');}},error=>errors.push(error));
await playMedia({play:async()=>{throw new Error('broken');}},error=>errors.push(error));
assert.equal(errors.length,1);
assert.equal(errors[0].message,'broken');
const hotkeys=await import('../dist/esm/player/hotkeys.js');
const actions=[];
hotkeys.bindPlayerHotkeys({seekBySeconds:n=>actions.push(n),seekBySubtitle:n=>actions.push(`cue:${n}`),toggleFullscreen(){},stepFrame(){},togglePlayback:()=>actions.push('play'),replaySubtitle(){},focusSearch(){},toggleSubtitles(){}});
document.dispatchEvent(new dom.window.KeyboardEvent('keydown',{code:'ArrowRight',shiftKey:true,bubbles:true,cancelable:true}));
document.getElementById('ankiUrl').dispatchEvent(new dom.window.KeyboardEvent('keydown',{code:'Space',bubbles:true,cancelable:true}));
assert.deepEqual(actions,[5]);
let calls=[];
globalThis.fetch=async(url,options)=>{calls.push({url,options});return new Response(JSON.stringify({ok:true,filename:'episode.mkv',candidates:[]}));};
const {uploadVideoInBackground}=await import('../dist/esm/video/upload.js');
await uploadVideoInBackground(new File(['video'],'episode.mkv'));
assert.equal(state.currentVideoFile,'episode.mkv');
assert.equal(calls.find(call=>String(call.url).endsWith('/upload-video')).options.method,'POST');
globalThis.fetch=async()=>{throw 'offline';};
await uploadVideoInBackground(new File(['video'],'other.mkv'));
assert.equal(state.currentVideoFile,'episode.mkv');
assert.ok(document.querySelector('.mp-toast-error').textContent.includes('offline'));
const progress=await import('../dist/esm/video/progress.js');
state.currentLibraryEpisodeId=12;
Object.defineProperty(video,'duration',{configurable:true,value:100});
video.currentTime=20;
progress.resetLibraryProgressTracking();
video.currentTime=25;
let payload;
globalThis.fetch=async(_url,options)=>{payload=JSON.parse(options.body);return new Response(JSON.stringify({progress:{watched_seconds:5}}));};
await progress.saveLibraryWatchProgress({force:true,skipAutoCompletePrompt:true});
assert.equal(payload.watchedDeltaSeconds,5);
video.currentTime=70;
assert.equal(progress.getLibraryWatchedDeltaSeconds(70),0);
globalThis.fetch=async()=>new Response(JSON.stringify({ok:false,error:{message:'failed'}}),{status:500});
await assert.rejects(progress.saveLibraryWatchProgress({force:true,rethrowErrors:true}),/failed/);
assert.equal(progress.libraryProgressSaveInFlightState.value,false);
state.currentLibraryEpisodeId=null;
const settings=await import('../dist/esm/player/settings.js');
const storage=await import('../dist/esm/player/settings-storage.js');
document.getElementById('ankiUrl').value='http://localhost:8765';
document.getElementById('highlightDeckNames').value='One, Two\nThree';
assert.equal(storage.collectSettings().ankiUrl,'http://localhost:8765');
globalThis.fetch=async(_url,options)=>{payload=JSON.parse(options.body);return new Response('{}');};
await storage.saveAnkiHighlightAutoRefreshSettings({...storage.collectSettings(),highlightDeckNames:'One, Two\nThree'});
assert.deepEqual(payload.decks,['One','Two','Three']);
const {bindPlayerEvents}=await import('../dist/esm/player/event-bindings.js');
bindPlayerEvents();
state.currentVideoFile=null;
let deleted=false;
globalThis.fetch=async()=>{deleted=true;return new Response('{}');};
await document.getElementById('deleteVideoBtn').onclick();
assert.equal(deleted,false);
const delay=document.getElementById('globalSubDelay');
delay.value='1.5';delay.dispatchEvent(new Event('input'));
assert.equal(state.globalSubDelay,1.5);
clearTimeout(settings.settingsAutosaveTimerState.value);
dom.window.close();
